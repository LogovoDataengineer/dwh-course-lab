-- Урок 17: источник для CDC — схема cdc в базе сайта: заказы и процедура «приложения», которое их меняет.
SET client_min_messages = warning;
DROP SCHEMA IF EXISTS cdc CASCADE;
CREATE SCHEMA cdc;
SELECT setseed(0.1717) \g /dev/null
CREATE TABLE cdc.orders (order_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id integer NOT NULL,
                         status text NOT NULL, amount numeric(10, 2) NOT NULL, updated_at timestamptz NOT NULL DEFAULT now());
INSERT INTO cdc.orders (order_id, customer_id, status, amount, updated_at)
SELECT o, 1 + floor(random() * 20000)::int,
       (ARRAY['created','paid','shipped','delivered','delivered','cancelled'])[1 + floor(random() * 6)::int],
       round((300 + random() * 9000)::numeric, -1), now() - interval '10 days' + o * interval '17 seconds'
FROM generate_series(1, 50000) AS o;
SELECT setval(pg_get_serial_sequence('cdc.orders', 'order_id'), 50000) \g /dev/null

-- Приложение: каждые 10 мс транзакция — новый заказ, смена статуса или удаление отменённого заказа (2%).
CREATE PROCEDURE cdc.work(seconds integer) LANGUAGE plpgsql AS $$
DECLARE stop timestamptz := clock_timestamp() + seconds * interval '1 second'; r double precision;
BEGIN
  WHILE clock_timestamp() < stop LOOP
    r := random();
    IF r < 0.45 THEN
      INSERT INTO cdc.orders (customer_id, status, amount) VALUES (1 + floor(random() * 20000)::int, 'created', round((300 + random() * 9000)::numeric, -1));
    ELSIF r < 0.98 THEN
      UPDATE cdc.orders SET status = CASE status WHEN 'created' THEN 'paid' WHEN 'paid' THEN 'shipped' WHEN 'shipped' THEN 'delivered' ELSE status END,
                            updated_at = now()
      WHERE order_id = (SELECT max(order_id) FROM cdc.orders) - floor(random() * 2000)::int;
    ELSE
      DELETE FROM cdc.orders WHERE order_id = (SELECT order_id FROM cdc.orders WHERE status = 'cancelled' ORDER BY random() LIMIT 1);
    END IF;
    COMMIT;
    PERFORM pg_sleep(0.01);
  END LOOP;
END $$;
