-- Урок 15: «приложение» магазина в базе сайта — схема app. Заказы меняются, пока хранилище их загружает.
-- updated_at ставит само приложение: now() — время НАЧАЛА транзакции, как у большинства ORM.
SET client_min_messages = warning;
DROP SCHEMA IF EXISTS app CASCADE;
CREATE SCHEMA app;
SELECT setseed(0.1515) \g /dev/null
CREATE TABLE app.orders (order_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id integer NOT NULL,
                         status text NOT NULL, amount numeric(10, 2) NOT NULL, updated_at timestamptz NOT NULL);
INSERT INTO app.orders (order_id, customer_id, status, amount, updated_at)
SELECT o, 1 + floor(random() * 20000)::int,
       (ARRAY['created','paid','shipped','delivered','delivered','delivered','cancelled'])[1 + floor(random() * 7)::int],
       round((300 + random() * 9000)::numeric, -1),
       now() - interval '30 days' + o * interval '25 seconds'
FROM generate_series(1, 100000) AS o;
SELECT setval(pg_get_serial_sequence('app.orders', 'order_id'), 100000) \g /dev/null
CREATE INDEX ON app.orders (updated_at);

-- Обычная работа: каждые 20 мс короткая транзакция — новый заказ или смена статуса.
CREATE PROCEDURE app.work_fast(seconds integer) LANGUAGE plpgsql AS $$
DECLARE stop timestamptz := clock_timestamp() + seconds * interval '1 second';
BEGIN
  WHILE clock_timestamp() < stop LOOP
    IF random() < 0.5 THEN
      INSERT INTO app.orders (customer_id, status, amount, updated_at)
      VALUES (1 + floor(random() * 20000)::int, 'created', round((300 + random() * 9000)::numeric, -1), now());
    ELSE
      UPDATE app.orders SET status = CASE status WHEN 'created' THEN 'paid' WHEN 'paid' THEN 'shipped' ELSE 'delivered' END,
                            updated_at = now()
      WHERE order_id = (SELECT max(order_id) FROM app.orders) - floor(random() * 3000)::int;
    END IF;
    COMMIT;
    PERFORM pg_sleep(0.02);
  END LOOP;
END $$;

-- Тяжёлые операции: раз в несколько секунд оформление заказа с проверкой склада и оплаты — транзакция
-- длится 3–5 секунд. updated_at = now() — момент её начала, а видна строка станет только после COMMIT.
CREATE PROCEDURE app.work_slow(seconds integer) LANGUAGE plpgsql AS $$
DECLARE stop timestamptz := clock_timestamp() + seconds * interval '1 second';
BEGIN
  WHILE clock_timestamp() < stop LOOP
    UPDATE app.orders SET status = 'paid', amount = amount + 10, updated_at = now()
    WHERE order_id = (SELECT max(order_id) FROM app.orders) - floor(random() * 500)::int;
    PERFORM pg_sleep(3 + random() * 2);
    COMMIT;
    PERFORM pg_sleep(random());
  END LOOP;
END $$;
ANALYZE app.orders;
